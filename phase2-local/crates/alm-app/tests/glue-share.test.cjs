const assert = require("node:assert/strict");
const { File } = require("node:buffer");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { test } = require("node:test");
const { runInNewContext } = require("node:vm");

const glue = readFileSync(join(__dirname, "../ui/glue.js"), "utf8");
const png = { name: "Bill-42.png", mime: "image/png", bytes: [137, 80, 78, 71, 0, 255] };

function harness({ navigator = {}, android, output = png, denied = false } = {}) {
  const calls = [];
  const notes = [];
  let click;
  let started;
  const ready = new Promise((resolve) => { started = resolve; });
  const view = {
    addEventListener() {},
    prepend(node) { notes.push(node); },
    querySelector: (selector) => selector === "#screen-nav" ? { content: {}, dataset: {} } : null,
    set innerHTML(_) { started(); },
  };
  const elements = {
    app: { addEventListener(type, listener) { if (type === "click") click = listener; } },
    view,
    nav: { replaceChildren() {} },
    "top-actions": { replaceChildren() {} },
    ttl: {},
    tsub: {},
  };
  const document = {
    getElementById: (id) => elements[id] ?? null,
    createElement: () => ({ setAttribute(name, value) { this[name] = value; } }),
  };
  const invoke = async (command, args) => {
    if (command === "start") return "";
    calls.push({ command, args: JSON.parse(JSON.stringify(args)) });
    if (denied) throw new Error("access denied");
    return args.webShare ? output : "/app/outputs/Bill-42.png";
  };
  runInNewContext(glue, {
    document, navigator, File, Uint8Array, btoa, setTimeout,
    window: { __TAURI__: { core: { invoke } }, AlmAndroid: android },
  });
  return {
    calls, notes, ready,
    click: (dataset = { action: "share_file", command: "bill_image_share", id: "42" }) =>
      click({ target: { closest: (selector) => selector.includes("data-fill") ? null : { dataset } } }),
  };
}

test("a supported desktop Web Share hands off the generated file without saving", async () => {
  let shared;
  const h = harness({ navigator: {
    canShare: ({ files }) => files.length === 1 && files[0].type === "image/png",
    share: async (data) => { shared = data; },
  } });
  await h.ready;
  await h.click();
  assert.equal(shared.files[0].name, png.name);
  assert.equal(shared.files[0].type, png.mime);
  assert.deepEqual([...new Uint8Array(await shared.files[0].arrayBuffer())], png.bytes);
  assert.deepEqual(h.calls, [{ command: "bill_image_share", args: { id: "42", q: "", webShare: true } }]);
  assert.deepEqual(h.notes, []);
});

test("a declined Web Share does not save, reveal, or show an error", async () => {
  const h = harness({ navigator: {
    canShare: () => true,
    share: async () => { throw Object.assign(new Error("cancelled"), { name: "AbortError" }); },
  } });
  await h.ready;
  await h.click();
  assert.equal(h.calls.length, 1);
  assert.equal(h.calls[0].args.webShare, true);
  assert.deepEqual(h.notes, []);
});

test("an unsupported file share falls back through the same save and reveal command", async () => {
  const h = harness({ navigator: { canShare: () => false, share: async () => assert.fail("shared") } });
  await h.ready;
  await h.click();
  assert.deepEqual(h.calls.map(({ args }) => args.webShare), [true, false]);
  assert.equal(h.notes[0].textContent, "Saved /app/outputs/Bill-42.png");
});

test("a failed capability probe falls back to save and reveal", async () => {
  const h = harness({ navigator: {
    canShare: () => { throw new TypeError("file sharing unavailable"); },
    share: async () => assert.fail("shared"),
  } });
  await h.ready;
  await h.click();
  assert.deepEqual(h.calls.map(({ args }) => args.webShare), [true, false]);
  assert.equal(h.notes[0].textContent, "Saved /app/outputs/Bill-42.png");
});

test("an unavailable Web Share saves directly through the existing command", async () => {
  const h = harness();
  await h.ready;
  await h.click();
  assert.deepEqual(h.calls, [{ command: "bill_image_share", args: { id: "42", q: "", webShare: false } }]);
  assert.equal(h.notes[0].textContent, "Saved /app/outputs/Bill-42.png");
});

test("a Web Share failure other than a decline falls back to save and reveal", async () => {
  const h = harness({ navigator: {
    canShare: () => true,
    share: async () => { throw Object.assign(new Error("activation expired"), { name: "NotAllowedError" }); },
  } });
  await h.ready;
  await h.click();
  assert.deepEqual(h.calls.map(({ args }) => args.webShare), [true, false]);
  assert.equal(h.notes[0].textContent, "Saved /app/outputs/Bill-42.png");
});

test("Android shares generated bytes rather than accepting a filesystem path", async () => {
  const shared = [];
  const h = harness({ android: { shareFile: (name, bytes) => shared.push({ name, bytes }) } });
  await h.ready;
  await h.click();
  assert.equal(h.calls[0].args.webShare, true);
  assert.equal(shared[0].name, png.name);
  assert.deepEqual([...Buffer.from(shared[0].bytes, "base64")], png.bytes);
});

test("a denied owner command never reaches a platform share or fallback", async () => {
  let shared = false;
  const h = harness({ denied: true, navigator: {
    canShare: () => true,
    share: async () => { shared = true; },
  } });
  await h.ready;
  await h.click();
  assert.equal(shared, false);
  assert.equal(h.calls.length, 1);
  assert.equal(h.notes[0].role, "alert");
});

test("a denied owner command cannot reach the Android bridge", async () => {
  let shared = false;
  const h = harness({ denied: true, android: { shareFile: () => { shared = true; } } });
  await h.ready;
  await h.click();
  assert.equal(shared, false);
  assert.equal(h.calls.length, 1);
  assert.equal(h.notes[0].role, "alert");
});

test("an export uses the same file handoff with its original command and MIME", async () => {
  let shared;
  const output = { name: "ALM-sales.csv", mime: "text/csv", bytes: [97, 44, 98, 10] };
  const h = harness({ output, navigator: {
    canShare: () => true,
    share: async (data) => { shared = data; },
  } });
  await h.ready;
  await h.click({ action: "share_file", command: "export_file", q: "csv" });
  assert.deepEqual(h.calls[0], { command: "export_file", args: { id: "0", q: "csv", webShare: true } });
  assert.equal(shared.files[0].name, output.name);
  assert.equal(shared.files[0].type, output.mime);
  assert.deepEqual([...new Uint8Array(await shared.files[0].arrayBuffer())], output.bytes);
});

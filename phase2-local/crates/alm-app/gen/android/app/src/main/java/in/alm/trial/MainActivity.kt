package `in`.alm.trial

import android.content.ClipData
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.print.PrintAttributes
import android.print.PrintManager
import android.util.Base64
import android.view.View
import android.view.WindowManager
import android.webkit.JavascriptInterface
import android.webkit.WebView
import androidx.activity.enableEdgeToEdge
import androidx.core.content.FileProvider
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import java.io.File
import java.util.UUID

class MainActivity : TauriActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    enableEdgeToEdge()
    super.onCreate(savedInstanceState)

    @Suppress("DEPRECATION") // Request IME inset delivery to the edge-to-edge content.
    window.setSoftInputMode(WindowManager.LayoutParams.SOFT_INPUT_ADJUST_RESIZE)
    val content = findViewById<View>(android.R.id.content)
    ViewCompat.setOnApplyWindowInsetsListener(content) { view, insets ->
      val safeArea = insets.getInsets(
        WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.displayCutout(),
      )
      // The WebView does not shrink for the on-screen keyboard by itself: pad by the IME
      // height too, so the page's visible viewport ends at the keyboard's top edge.
      val ime = insets.getInsets(WindowInsetsCompat.Type.ime())
      val bottom = maxOf(safeArea.bottom, ime.bottom)
      view.setPadding(safeArea.left, safeArea.top, safeArea.right, bottom)
      insets.inset(safeArea.left, safeArea.top, safeArea.right, bottom)
    }
    ViewCompat.requestApplyInsets(content)
  }

  // Android's WebView has no window.print(); expose the platform print and share dialogs.
  override fun onWebViewCreate(webView: WebView) {
    webView.addJavascriptInterface(PlatformBridge(this, webView), "AlmAndroid")
  }
}

class PlatformBridge(private val activity: MainActivity, private val webView: WebView) {
  /** Opens the system print dialog for the current page; it offers printers and Save as PDF. */
  @JavascriptInterface
  fun print(title: String) {
    activity.runOnUiThread {
      val manager = activity.getSystemService(PrintManager::class.java)
      val name = title.ifBlank { "ALM document" }
      manager.print(
        name,
        webView.createPrintDocumentAdapter(name),
        PrintAttributes.Builder().setMediaSize(PrintAttributes.MediaSize.ISO_A4).build(),
      )
    }
  }

  /** Opens the system share sheet with plain text. */
  @JavascriptInterface
  fun share(text: String) {
    activity.runOnUiThread {
      val send = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_TEXT, text)
      }
      activity.startActivity(Intent.createChooser(send, "Share invoice"))
    }
  }

  /** Creates a shareable output from generated bytes without opening a caller-supplied path. */
  @JavascriptInterface
  fun shareFile(name: String, encoded: String): Boolean {
    if (name.isEmpty() || name == "." || name == ".." || File(name).name != name || '\\' in name) {
      return false
    }
    val mime = when (name.substringAfterLast('.', "").lowercase()) {
      "png" -> "image/png"
      "csv" -> "text/csv"
      "xls" -> "application/vnd.ms-excel"
      else -> return false
    }
    val directory = try {
      val outputs = File(activity.cacheDir.canonicalFile, "outputs")
      if (outputs.canonicalFile != outputs.absoluteFile) return false
      if (!outputs.isDirectory && !outputs.mkdirs()) return false
      File(outputs, "share-${UUID.randomUUID()}").also { if (!it.mkdir()) return false }
    } catch (error: Exception) {
      return false
    }
    val file = File(directory, name)
    val uri = try {
      file.writeBytes(Base64.decode(encoded, Base64.DEFAULT))
      FileProvider.getUriForFile(activity, "${activity.packageName}.fileprovider", file)
    } catch (error: Exception) {
      file.delete()
      directory.delete()
      return false
    }
    activity.runOnUiThread {
      val send = Intent(Intent.ACTION_SEND).apply {
        type = mime
        putExtra(Intent.EXTRA_STREAM, uri)
        clipData = ClipData.newRawUri(name, uri)
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      }
      val chooser = Intent.createChooser(send, "Share $name").apply {
        clipData = ClipData.newRawUri(name, uri)
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      }
      activity.startActivity(chooser)
    }
    return true
  }

  /**
   * Copies a file the user picked in the system file dialog (a content URI) to [dest], which
   * must lie inside this app's own data folder. Returns false when it cannot.
   */
  @JavascriptInterface
  fun copyIn(uri: String, dest: String): Boolean {
    val target = java.io.File(dest)
    if (!uri.startsWith("content://") ||
      !target.canonicalPath.startsWith(activity.dataDir.canonicalPath + "/")
    ) {
      return false
    }
    return try {
      activity.contentResolver.openInputStream(Uri.parse(uri)).use { input ->
        if (input == null) return false
        target.parentFile?.mkdirs()
        java.io.FileOutputStream(target).use { output -> input.copyTo(output) }
      }
      true
    } catch (error: Exception) {
      target.delete()
      false
    }
  }

  /** Opens a WhatsApp link (wa.me only) in WhatsApp or the browser. */
  @JavascriptInterface
  fun openUrl(url: String) {
    if (!url.startsWith("https://wa.me/")) return
    activity.runOnUiThread {
      activity.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(url)))
    }
  }
}

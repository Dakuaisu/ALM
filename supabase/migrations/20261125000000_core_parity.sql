-- Local development schema, continued: the command functions now follow the Rust core
-- (alm-core) exactly, as checked by the alm-sync differential suite. Synthetic slice only;
-- not the deployed schema (OPEN-002) and not an approved permission matrix (OPEN-004).
--
-- What changes, each matching the core:
--  * a sale's FIFO allocations are kept per line and lot (`sale_line_lots`); cancel returns
--    them to the same lots, restore takes them again from those lots, an edit takes extra
--    packets oldest lot first and returns fewer packets to this line's newest lots first;
--  * an edit freezes each line's unit cost once (cost / quantity, halves rounded up) and the
--    sale cost becomes the frozen unit cost times the new quantities;
--  * cancel and restore require a part-paid named bill and no stock movement since the bill's
--    last change (the global movement epoch), and are no-ops when already in that state;
--  * posting requires the selected directory customer with its directory name, a bill date
--    and 0 <= paid <= total; prices are checked before the customer and stock after both;
--  * receiving at a typed rate sets the product's buy rate and the supplier's quote; the lot
--    costs the typed rate, else the order line rate;
--  * Cash Book rows are numbered from 0 and never reuse a deleted number;
--  * the projection rows are the device's per-screen rows (`alm_sync::wire`): catalog at the
--    provisional rate, stock rows, sale items and balances, receipt slots and names, order
--    status, and the core's list orders.

alter table public.products
    add column provisional_minor bigint check (provisional_minor >= 0),
    add column ord bigint generated by default as identity;

alter table public.sales
    add column epoch bigint not null default 0,
    add column cost_minor bigint;

alter table public.sale_lines
    add column item text,
    add column frozen boolean not null default false,
    add column frozen_unit bigint;

-- Which lots each sale line took its packets from.
create table public.sale_line_lots (
    sale_id bigint not null references public.sales (id),
    position integer not null,
    lot_id bigint not null references public.product_lots (id) on delete cascade,
    quantity integer not null check (quantity > 0),
    primary key (sale_id, position, lot_id)
);
alter table public.sale_line_lots enable row level security;

alter table public.authority_state
    add column movement bigint not null default 0,
    add column next_cash bigint not null default 0;

alter table public.cash_days alter column id drop identity;

-- ---------------------------------------------------------------------------------------
-- Helpers.

create function alm_private.move()
returns bigint
language sql
set search_path = ''
as $$
    update public.authority_state set movement = movement + 1 where id = 1 returning movement;
$$;

-- Takes `p_quantity` packets for one sale line oldest lot first, recording each lot taken
-- from; returns their cost (null when any taken packet has no known cost).
create function alm_private.allocate(
    p_sale bigint, p_position integer, p_product bigint, p_quantity integer)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
    v_lot record;
    v_left integer := p_quantity;
    v_take integer;
    v_cost bigint := 0;
    v_known boolean := true;
begin
    for v_lot in
        select id, remaining, unit_cost_minor from public.product_lots
        where product_id = p_product and remaining > 0
        order by received_on nulls first, id
        for update
    loop
        exit when v_left = 0;
        v_take := least(v_left, v_lot.remaining);
        update public.product_lots set remaining = remaining - v_take where id = v_lot.id;
        insert into public.sale_line_lots values (p_sale, p_position, v_lot.id, v_take)
            on conflict (sale_id, position, lot_id)
            do update set quantity = public.sale_line_lots.quantity + excluded.quantity;
        if v_lot.unit_cost_minor is null then
            v_known := false;
        else
            v_cost := v_cost + v_take * v_lot.unit_cost_minor;
        end if;
        v_left := v_left - v_take;
    end loop;
    if v_left > 0 then
        raise exception 'insufficient_stock' using errcode = 'ALM04';
    end if;
    update public.products set stock = stock - p_quantity where id = p_product;
    return case when v_known then v_cost end;
end;
$$;

-- Returns `p_quantity` packets of one sale line to its newest lots first.
create function alm_private.release(
    p_sale bigint, p_position integer, p_product bigint, p_quantity integer)
returns void
language plpgsql
set search_path = ''
as $$
declare
    v_held record;
    v_left integer := p_quantity;
    v_back integer;
begin
    for v_held in
        select a.lot_id, a.quantity from public.sale_line_lots a
        join public.product_lots l on l.id = a.lot_id
        where a.sale_id = p_sale and a.position = p_position
        order by l.received_on desc nulls last, l.id desc
    loop
        exit when v_left = 0;
        v_back := least(v_left, v_held.quantity);
        update public.product_lots set remaining = remaining + v_back where id = v_held.lot_id;
        if v_back = v_held.quantity then
            delete from public.sale_line_lots
                where sale_id = p_sale and position = p_position and lot_id = v_held.lot_id;
        else
            update public.sale_line_lots set quantity = quantity - v_back
                where sale_id = p_sale and position = p_position and lot_id = v_held.lot_id;
        end if;
        v_left := v_left - v_back;
    end loop;
    if v_left > 0 then
        raise exception 'invalid_terms: release' using errcode = 'ALM05';
    end if;
    update public.products set stock = stock + p_quantity where id = p_product;
end;
$$;

-- A customer's balance: opening, plus every active bill's unpaid remainder, less receipts.
create function alm_private.customer_balance(p_customer text)
returns bigint
language sql
stable
set search_path = ''
as $$
    select coalesce((select opening_minor from public.customers where id = p_customer), 0)
        + coalesce((select sum(total_minor - paid_minor) from public.sales
            where customer_id = p_customer and not cancelled), 0)
        - coalesce((select sum(amount_minor) from public.receipts
            where customer_id = p_customer), 0);
$$;


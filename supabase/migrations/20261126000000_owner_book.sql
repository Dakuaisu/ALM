        update public.receipts r set
                after_invoice = (select next_no - 1 from public.invoice_counters
                    where series = 'sale'),
                created_ms = (extract(epoch from clock_timestamp()) * 1000)::bigint,
                selected_name = (select name from public.customers where id = r.customer_id)
            where r.id = (select max(id) from public.receipts);
        update public.customers set has_balance = true where id = p_terms ->> 'customer_id';
    end if;
    return v_out;
end;
$$;


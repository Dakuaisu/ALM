create function alm_private.revision()
returns bigint
language sql
stable
set search_path = ''
as $$
    select revision from public.authority_state where id = 1;
$$;

do $$
declare
    f text;
begin
    foreach f in array array['post_sale', 'set_sale_cancelled', 'edit_sale', 'record_receipt',
        'save_opening', 'save_product', 'add_supplier', 'receive_purchase_order', 'save_crate']
    loop
        execute format('alter function public.%I(text, jsonb) set schema alm_private', f);
        execute format('alter function alm_private.%I(text, jsonb) rename to %I', f, f || '_body');
        execute format('revoke all on function alm_private.%I(text, jsonb) from public, anon, authenticated',
            f || '_body');
    end loop;
end;
$$;

-- The customer's balance right after a bill changed.
create function alm_private.after_bill(p_draft text)
returns void
language sql
set search_path = ''
as $$
    update public.sales s set balance_after = alm_private.customer_balance(s.customer_id)
        where s.draft_id = p_draft;
    update public.customers c set has_balance = true
        from public.sales s where s.draft_id = p_draft and c.id = s.customer_id;
$$;

create function public.post_sale(p_request_id text, p_terms jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_before bigint := alm_private.revision();
    v_out jsonb := alm_private.post_sale_body(p_request_id, p_terms);
begin
    if alm_private.revision() > v_before then
        perform alm_private.after_bill(p_terms ->> 'draft_id');
    end if;
    return v_out;
end;
$$;

create function public.set_sale_cancelled(p_request_id text, p_terms jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_was boolean := (select cancelled from public.sales where draft_id = p_terms ->> 'draft_id');
    v_out jsonb := alm_private.set_sale_cancelled_body(p_request_id, p_terms);
begin
    -- A cancel or restore counts as a change of the bill, as an edit does.
    update public.sales set edits = edits + 1
        where draft_id = p_terms ->> 'draft_id' and cancelled is distinct from v_was;
    return v_out;
end;
$$;


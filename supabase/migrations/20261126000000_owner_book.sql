-- Each received line is recorded with its date and typed rate, and the product's running
-- average receipt cost moves as the core's does: (stock before x average + quantity x incoming)
-- / (stock after), halves up, where incoming is the typed rate or else the average itself.
create function public.receive_purchase_order(p_request_id text, p_terms jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_po bigint := (p_terms ->> 'po')::bigint;
    v_received jsonb := (select jsonb_object_agg(position, received)
        from public.purchase_lines where po_id = v_po);
    v_stock jsonb := (select jsonb_object_agg(id, stock) from public.products);
    v_before bigint := alm_private.revision();
    v_out jsonb := alm_private.receive_purchase_order_body(p_request_id, p_terms);
    v_line record;
    v_quantity integer;
    v_rate bigint;
    v_product public.products%rowtype;
    v_on_hand bigint;
    v_previous bigint;
    v_incoming bigint;
    v_day date := coalesce(alm_private.text_date(p_terms -> 'date'),
        alm_private.text_date(p_terms -> 'today'));
begin
    if alm_private.revision() = v_before then
        return v_out;
    end if;
    for v_line in select * from public.purchase_lines where po_id = v_po order by position loop
        v_quantity := v_line.received - (v_received ->> v_line.position::text)::integer;
        continue when v_quantity <= 0;
        v_rate := coalesce((p_terms -> 'lines' -> v_line.position ->> 'rate_minor')::bigint, 0);
        insert into public.purchase_receipts (po_id, position, receipt_date, quantity, rate_minor)
            values (v_po, v_line.position, v_day, v_quantity, v_rate);
        select * into v_product from public.products
            where id = v_line.product_id and purchase_item is not null;
        if not found then
            select * into v_product from public.products
                where purchase_item = v_line.item order by ord limit 1;
        end if;
        continue when v_product.id is null;
        v_on_hand := (v_stock ->> v_product.id::text)::bigint;
        v_previous := coalesce(v_product.purchase_avg_minor, v_product.purchase_buy_minor, 0);
        v_incoming := case when v_rate > 0 then v_rate else v_previous end;
        update public.products set
                purchase_avg_minor = (v_on_hand * v_previous + v_quantity * v_incoming
                    + (v_on_hand + v_quantity) / 2) / (v_on_hand + v_quantity),
                purchase_buy_minor = case when v_rate > 0 then v_rate else purchase_buy_minor end,
                purchase_cost_seq = coalesce(purchase_cost_seq,
                    nextval('alm_private.purchase_cost_seq'))
            where id = v_product.id;
        v_stock := jsonb_set(v_stock, array[v_product.id::text],
            to_jsonb(v_on_hand + v_quantity));
    end loop;
    return v_out;
end;
$$;

create function public.save_crate(p_request_id text, p_terms jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_before bigint := alm_private.revision();
    v_out jsonb := alm_private.save_crate_body(p_request_id, p_terms);
begin
    if alm_private.revision() > v_before then
        update public.authority_state
            set last_crate = greatest(last_crate, (v_out ->> 'created')::bigint) where id = 1;
    end if;
    return v_out;
end;
$$;


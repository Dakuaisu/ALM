-- Local development schema, continued: the Owner's book rows. `pull_projection` now also sends
-- `owner.book`: every row the Owner screens (Products, Suppliers and quotes, Order Planner,
-- Purchase Orders, Crates, Godown, Reorder, Rate List, Reports, Dashboard, GST Sales, Counter)
-- and the priced draft review are computed from, in the format `alm_core::projection::book`
-- reads. The device rebuilds its read-only view from them; the screens' arithmetic stays in the
-- core. Synthetic slice only; not the deployed schema (OPEN-002) nor a permission matrix
-- (OPEN-004): the book is Owner-only and a Manager pull never carries it.
--
-- The bookkeeping the book needs and the commands did not keep yet is added by wrapping each
-- command: the previous body moves to `alm_private.<name>_body` unchanged, and the public
-- function runs it, then (only when it committed new effects, i.e. the checkpoint advanced)
-- records the extra facts.

